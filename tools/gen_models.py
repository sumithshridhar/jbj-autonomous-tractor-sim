"""Generate Gazebo (SDF) models for each tractor and the field world from specs/*.json.

  python tools/gen_models.py

Writes ros2_ws/src/jbj_sim/models/<tractor_id>/model.sdf (+ model.config), models/cow|person/model.sdf and
ros2_ws/src/jbj_sim/worlds/field.sdf. Meshes come from blender/build_models.py.
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ros2_ws" / "src" / "jbj_sim"))
from jbj_sim.spec import load, track_of, tractor_geometry  # noqa: E402

PKG = ROOT / "ros2_ws" / "src" / "jbj_sim"
MODELS = PKG / "models"

WHEEL_MASS_REAR = 250.0   # ASSUMPTION: 460/85 R34-R38 tyre + steel rim (+ some liquid ballast)
WHEEL_MASS_FRONT = 110.0  # ASSUMPTION: 380/85 R24-R28 tyre + rim
TYRE_MU = 0.8             # ASSUMPTION: tractor tyre on tilled soil


def inertia_box(m, x, y, z):
    return m * (y * y + z * z) / 12, m * (x * x + z * z) / 12, m * (x * x + y * y) / 12


def inertia_cyl_y(m, r, h):   # cylinder with its axis along Y
    i_side = m * (3 * r * r + h * h) / 12
    return i_side, m * r * r / 2, i_side


def inertial(m, ixx, iyy, izz, pose="0 0 0 0 0 0"):
    return (f"<inertial><pose>{pose}</pose><mass>{m:.1f}</mass><inertia><ixx>{ixx:.2f}</ixx><ixy>0</ixy><ixz>0</ixz>"
            f"<iyy>{iyy:.2f}</iyy><iyz>0</iyz><izz>{izz:.2f}</izz></inertia></inertial>")


def surface(mu):
    return f"<surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface>"


def wheel_link(name, x, y, r, w, mass, mesh):
    return f"""
    <link name="{name}">
      <pose>{x:.4f} {y:.4f} {r:.4f} 0 0 0</pose>
      {inertial(mass, *inertia_cyl_y(mass, r, w))}
      <collision name="c"><pose>0 0 0 {math.pi/2:.5f} 0 0</pose>
        <geometry><cylinder><radius>{r:.4f}</radius><length>{w:.3f}</length></cylinder></geometry>{surface(TYRE_MU)}</collision>
      <visual name="v"><geometry><mesh><uri>{mesh}</uri></mesh></geometry></visual>
    </link>"""


def tractor_sdf(tid, t, g, kit):
    L, tr = g["L"], g["track"]
    rr, rf = g["rear"]["d"] / 2, g["front"]["d"] / 2
    wr, wf = g["rear"]["w"], g["front"]["w"]
    m_body = t["mass_kg"] - 2 * WHEEL_MASS_REAR - 2 * WHEEL_MASS_FRONT
    bx, by, bz = g["x_front"] + 0.75, 1.3, g["h_roof"] - g["clearance"]
    com = f"{0.42 * L:.3f} 0 0.95 0 0 0"   # ASSUMPTION: ~42 % of the wheelbase ahead of the rear axle, 0.95 m high
    H = g["h_roof"]
    ant = kit["gnss"]["antenna_baseline_m"] / 2
    lid = kit["lidar"]
    lx, ly, lz = g["lidar_xyz"]
    h_samples, v_samples = 720, 40     # 28,800 rays per 10 Hz frame, close to the Mid-360's 20,000 points/frame
    steer_max = math.radians(t["steering_angle_deg"])
    m = f"model://{tid}/meshes"
    impl = "model://planter/meshes/planter.obj"
    return f"""<?xml version="1.0"?>
<!-- Generated by tools/gen_models.py from specs/tractors.json + specs/kit.json. Do not edit by hand. -->
<sdf version="1.10">
  <model name="{tid}">
    <link name="base_link">
      {inertial(m_body, *inertia_box(m_body, bx, by, bz), com)}
      <collision name="chassis"><pose>{(g['x_front'] - 0.75) / 2:.3f} 0 {g['clearance'] + bz / 2:.3f} 0 0 0</pose>
        <geometry><box><size>{bx:.3f} {by:.3f} {bz:.3f}</size></box></geometry></collision>
      <visual name="body"><geometry><mesh><uri>{m}/body.obj</uri></mesh></geometry></visual>
      <visual name="kit"><geometry><mesh><uri>{m}/kit.obj</uri></mesh></geometry></visual>
      <visual name="planter"><geometry><mesh><uri>{impl}</uri></mesh></geometry></visual>
      <sensor name="gnss_left" type="navsat">
        <pose>0.30 {ant:.3f} {H + 0.06:.3f} 0 0 0</pose><always_on>1</always_on><update_rate>{kit['gnss']['rate_hz']}</update_rate>
        <topic>/gnss/left</topic>
      </sensor>
      <sensor name="gnss_right" type="navsat">
        <pose>0.30 {-ant:.3f} {H + 0.06:.3f} 0 0 0</pose><always_on>1</always_on><update_rate>{kit['gnss']['rate_hz']}</update_rate>
        <topic>/gnss/right</topic>
      </sensor>
      <sensor name="lidar" type="gpu_lidar">
        <!-- Livox Mid-360 mounted upside down (roll = pi): its -7..52 deg vertical field of view looks down at the ground ahead -->
        <pose>{lx:.3f} {ly:.3f} {lz:.3f} {math.pi:.5f} 0 0</pose>
        <topic>/lidar</topic><update_rate>{lid['frame_rate_hz']}</update_rate><always_on>1</always_on>
        <lidar>
          <scan>
            <horizontal><samples>{h_samples}</samples><resolution>1</resolution><min_angle>{-math.pi:.5f}</min_angle><max_angle>{math.pi:.5f}</max_angle></horizontal>
            <vertical><samples>{v_samples}</samples><resolution>1</resolution><min_angle>{math.radians(lid['fov_v_min_deg']):.5f}</min_angle><max_angle>{math.radians(lid['fov_v_max_deg']):.5f}</max_angle></vertical>
          </scan>
          <range><min>{lid['blind_zone_m']}</min><max>{lid['range_m_10pct']}</max><resolution>0.01</resolution></range>
          <noise><type>gaussian</type><mean>0</mean><stddev>{lid['range_sigma_m']}</stddev></noise>
        </lidar>
      </sensor>
    </link>
    {wheel_link("rear_left_wheel", 0.0, tr / 2, rr, wr, WHEEL_MASS_REAR, m + "/wheel_rear.obj")}
    {wheel_link("rear_right_wheel", 0.0, -tr / 2, rr, wr, WHEEL_MASS_REAR, m + "/wheel_rear.obj")}
    <link name="front_left_steer"><pose>{L:.4f} {tr / 2:.4f} {rf:.4f} 0 0 0</pose>{inertial(15, 0.3, 0.3, 0.3)}</link>
    <link name="front_right_steer"><pose>{L:.4f} {-tr / 2:.4f} {rf:.4f} 0 0 0</pose>{inertial(15, 0.3, 0.3, 0.3)}</link>
    {wheel_link("front_left_wheel", L, tr / 2, rf, wf, WHEEL_MASS_FRONT, m + "/wheel_front.obj")}
    {wheel_link("front_right_wheel", L, -tr / 2, rf, wf, WHEEL_MASS_FRONT, m + "/wheel_front.obj")}
    <joint name="rear_left_wheel_joint" type="revolute"><parent>base_link</parent><child>rear_left_wheel</child>
      <axis><xyz>0 1 0</xyz><limit><lower>-1e16</lower><upper>1e16</upper></limit></axis></joint>
    <joint name="rear_right_wheel_joint" type="revolute"><parent>base_link</parent><child>rear_right_wheel</child>
      <axis><xyz>0 1 0</xyz><limit><lower>-1e16</lower><upper>1e16</upper></limit></axis></joint>
    <joint name="front_left_steer_joint" type="revolute"><parent>base_link</parent><child>front_left_steer</child>
      <axis><xyz>0 0 1</xyz><limit><lower>{-steer_max:.4f}</lower><upper>{steer_max:.4f}</upper><effort>1000000</effort></limit></axis></joint>
    <joint name="front_right_steer_joint" type="revolute"><parent>base_link</parent><child>front_right_steer</child>
      <axis><xyz>0 0 1</xyz><limit><lower>{-steer_max:.4f}</lower><upper>{steer_max:.4f}</upper><effort>1000000</effort></limit></axis></joint>
    <joint name="front_left_wheel_joint" type="revolute"><parent>front_left_steer</parent><child>front_left_wheel</child>
      <axis><xyz>0 1 0</xyz><limit><lower>-1e16</lower><upper>1e16</upper></limit></axis></joint>
    <joint name="front_right_wheel_joint" type="revolute"><parent>front_right_steer</parent><child>front_right_wheel</child>
      <axis><xyz>0 1 0</xyz><limit><lower>-1e16</lower><upper>1e16</upper></limit></axis></joint>
    <plugin filename="gz-sim-ackermann-steering-system" name="gz::sim::systems::AckermannSteering">
      <left_joint>rear_left_wheel_joint</left_joint><right_joint>rear_right_wheel_joint</right_joint>
      <left_steering_joint>front_left_steer_joint</left_steering_joint><right_steering_joint>front_right_steer_joint</right_steering_joint>
      <kingpin_width>{tr:.3f}</kingpin_width><steering_limit>{steer_max:.4f}</steering_limit><steer_p_gain>10.0</steer_p_gain>
      <wheel_base>{L:.4f}</wheel_base><wheel_separation>{tr:.3f}</wheel_separation><wheel_radius>{rr:.4f}</wheel_radius>
      <min_velocity>-3.0</min_velocity><max_velocity>8.4</max_velocity>
      <min_acceleration>-3.0</min_acceleration><max_acceleration>1.5</max_acceleration>
      <topic>/model/tractor/cmd_vel</topic><odom_topic>/model/tractor/wheel_odom</odom_topic>
    </plugin>
    <plugin filename="gz-sim-odometry-publisher-system" name="gz::sim::systems::OdometryPublisher">
      <odom_frame>field</odom_frame><robot_base_frame>base_link</robot_base_frame><odom_publish_frequency>20</odom_publish_frequency>
      <odom_topic>/model/tractor/ground_truth</odom_topic><dimensions>3</dimensions>
    </plugin>
    <plugin filename="gz-sim-joint-state-publisher-system" name="gz::sim::systems::JointStatePublisher">
      <topic>/model/tractor/joint_state</topic>
    </plugin>
  </model>
</sdf>
"""


def obstacle_sdf(name, mesh, size, z):
    sx, sy, sz = size
    return f"""<?xml version="1.0"?>
<sdf version="1.10">
  <model name="{name}">
    <static>true</static>
    <link name="link">
      <collision name="c"><pose>0 0 {z:.3f} 0 0 0</pose><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>
      <visual name="v"><geometry><mesh><uri>model://{name}/meshes/{mesh}</uri></mesh></geometry></visual>
    </link>
  </model>
</sdf>
"""


def world_sdf(field):
    pts = field["boundary_enu_m"]
    # fence posts every ~10 m, 1.5 m outside the field edge (the field edge is the cultivated boundary)
    cx = sum(p[0] for p in pts) / len(pts)
    cy = sum(p[1] for p in pts) / len(pts)
    posts = []
    for i in range(len(pts)):
        (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % len(pts)]
        n = max(1, int(math.hypot(x1 - x0, y1 - y0) // 10))
        for k in range(n):
            x, y = x0 + (x1 - x0) * k / n, y0 + (y1 - y0) * k / n
            d = math.hypot(x - cx, y - cy)
            x, y = x + (x - cx) / d * 1.5, y + (y - cy) / d * 1.5
            posts.append(f"""<visual name="post{len(posts)}"><pose>{x:.2f} {y:.2f} 0.6 0 0 0</pose>
          <geometry><cylinder><radius>0.06</radius><length>1.2</length></cylinder></geometry>
          <material><diffuse>0.35 0.25 0.15 1</diffuse></material></visual>""")
    return f"""<?xml version="1.0"?>
<!-- Generated by tools/gen_models.py from specs/field.json. -->
<sdf version="1.10">
  <world name="field">
    <physics name="2ms" type="dart"><max_step_size>0.002</max_step_size><real_time_factor>0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model><world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{field['origin_lat']}</latitude_deg><longitude_deg>{field['origin_lon']}</longitude_deg>
      <elevation>{field['origin_alt_m']}</elevation><heading_deg>0</heading_deg>
    </spherical_coordinates>
    <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.55 0.68 0.85 1</background><shadows>true</shadows></scene>
    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 100 0 0 0</pose>
      <diffuse>1 0.97 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.4 0.3 -0.85</direction></light>
    <model name="ground"><static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>2000 2000</size></plane></geometry>
          <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>2000 2000</size></plane></geometry>
          <material><ambient>0.30 0.17 0.09 1</ambient><diffuse>0.42 0.24 0.13 1</diffuse></material></visual>
      </link>
    </model>
    <model name="fence"><static>true</static><link name="link">
        {"".join(posts)}
    </link></model>
  </world>
</sdf>
"""


def main():
    tr = load("tractors", ROOT / "specs")
    kit = load("kit", ROOT / "specs")
    field = load("field", ROOT / "specs")
    for tid, t in tr["models"].items():
        g = tractor_geometry(t, track_of(t, tr))
        d = MODELS / tid
        d.mkdir(parents=True, exist_ok=True)
        (d / "model.sdf").write_text(tractor_sdf(tid, t, g, kit))
        (d / "model.config").write_text(f'<?xml version="1.0"?><model><name>{tid}</name><version>1.0</version>'
                                        f'<sdf version="1.10">model.sdf</sdf><description>{t["name"]} with retrofit autonomy kit</description></model>\n')
    for name, mesh, size, z in (("cow", "cow.obj", (2.1, 0.62, 1.35), 0.675), ("person", "person.obj", (0.3, 0.6, 1.75), 0.875)):
        (MODELS / name / "model.sdf").write_text(obstacle_sdf(name, mesh, size, z))
        (MODELS / name / "model.config").write_text(f'<?xml version="1.0"?><model><name>{name}</name><version>1.0</version><sdf version="1.10">model.sdf</sdf></model>\n')
    (PKG / "worlds").mkdir(exist_ok=True)
    (PKG / "worlds" / "field.sdf").write_text(world_sdf(field))
    print("models:", ", ".join(tr["models"]), "+ cow, person; world: worlds/field.sdf")


main()
